package com.shadowclient.module.setting;

import com.google.gson.JsonElement;
import com.google.gson.JsonPrimitive;

public final class NumberSetting extends Setting<Double> {
    private final double min;
    private final double max;
    private final double step;

    public NumberSetting(String name, double value, double min, double max, double step) {
        super(name, value);
        this.min = min;
        this.max = max;
        this.step = step;
    }

    public double min() { return min; }
    public double max() { return max; }
    public double step() { return step; }
    public float floatValue() { return value.floatValue(); }
    public int intValue() { return value.intValue(); }

    @Override
    public void set(Double v) {
        double snapped = Math.round(v / step) * step;
        value = Math.max(min, Math.min(max, snapped));
    }

    @Override public JsonElement serialize() { return new JsonPrimitive(value); }

    @Override public void deserialize(JsonElement e) { set(e.getAsDouble()); }
}
